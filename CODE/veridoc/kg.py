"""Stage 5a: the provenance-complete knowledge graph.

Only verified (or human-verified) facts are loaded. Every property assertion
is backed by at least one Evidence node (document, page, bbox, span).
Outputs: Turtle (RDF), Cypher (for Neo4j) and summary statistics.
"""
from __future__ import annotations
import json
from collections import defaultdict
from rdflib import Graph, Literal, Namespace, RDF, URIRef
from rdflib.namespace import XSD

from . import config
from .verifier import EX, ENTITY_OF, XSD_OF
from .fields import FIELD_TYPES
from .keys import all_keys, name_key

LOADED = ("verified", "human_verified")
# Individuals of the one worksite case live in their own namespace; classes and properties are in EX
# (declared in CODE/ontology/ontology.ttl, generated by veridoc/ontology.py).
INST = Namespace("http://veridoc.example/case/1#")
# entity relations of the single worksite case in D1
RELATIONS = [("Certificate", "issued_under", "Group"), ("Certificate", "insures", "Insured"), ("Certificate", "has_rider", "Rider")]
STAGES = ["0_process_map", "1_quote", "2_master_application", "3_enrollment", "4_policy", "5_certificate"]


def build(facts: list) -> tuple[Graph, list, dict]:
    """Returns (rdf graph, cypher statements, stats)."""
    g = Graph(); g.bind("ex", EX); g.bind("case", INST)
    ind = lambda e: INST[e.lower()]                     # the Certificate individual is case:certificate
    cy, loaded = [], [f for f in facts if f.status in LOADED and f.field in ENTITY_OF]
    assertions = defaultdict(list)                      # (entity, field, value) -> evidence facts
    for f in loaded:
        assertions[(ENTITY_OF[f.field], f.field, f.normalized)].append(f)

    entities = sorted({k[0] for k in assertions})
    # deterministic canonical key per entity (veridoc/keys.py); None when the fields a key needs are missing
    values = defaultdict(dict)
    for (ent, field, value) in assertions:
        values[ent][field] = name_key(value) if FIELD_TYPES.get(field) == "name" else value
    keys = all_keys(values)
    for e in entities:
        g.add((ind(e), RDF.type, EX[e]))
        cy.append(f"MERGE (:{e} {{id: '{e}'}});")
        key, basis = keys.get(e, (None, None))
        if key:
            g.add((ind(e), EX.canonical_key, Literal(key))); g.add((ind(e), EX.key_basis, Literal(basis)))
            k = key.replace("'", "\\'")
            cy.append(f"MATCH (e:{e} {{id:'{e}'}}) SET e.canonical_key='{k}', e.key_basis='{basis}';")
    for a, rel, b in RELATIONS:
        if a in entities and b in entities:
            g.add((ind(a), EX[rel], ind(b)))
            cy.append(f"MATCH (a:{a} {{id:'{a}'}}),(b:{b} {{id:'{b}'}}) MERGE (a)-[:{rel.upper()}]->(b);")
    for i, s in enumerate(STAGES):
        cy.append(f"MERGE (:WorkflowStage {{id: '{s}'}});")
        g.add((INST['stage_' + s], RDF.type, EX.WorkflowStage))
        if i:
            cy.append(f"MATCH (a:WorkflowStage {{id:'{STAGES[i-1]}'}}),(b:WorkflowStage {{id:'{s}'}}) MERGE (a)-[:PRECEDES]->(b);")
            g.add((INST['stage_' + STAGES[i - 1]], EX.precedes, INST['stage_' + s]))
    for doc_id in sorted({f.doc_id for f in loaded}):
        title = config.DOC_TITLES[doc_id].replace("'", "")
        g.add((INST['doc_' + doc_id], RDF.type, EX.Document)); g.add((INST['doc_' + doc_id], EX.produced_at, INST['stage_' + config.DOC_STAGE[doc_id]]))
        g.add((INST['doc_' + doc_id], EX.title, Literal(config.DOC_TITLES[doc_id])))
        cy.append(f"MERGE (d:Document {{id:'{doc_id}'}}) SET d.title='{title}';")
        cy.append(f"MATCH (d:Document {{id:'{doc_id}'}}),(s:WorkflowStage {{id:'{config.DOC_STAGE[doc_id]}'}}) MERGE (d)-[:PRODUCED_AT]->(s);")

    n_ev = 0
    for (ent, field, value), evs in sorted(assertions.items()):
        ftype = FIELD_TYPES.get(field, "text")
        g.add((ind(ent), EX[field], Literal(value, datatype=XSD_OF[ftype]) if ftype in XSD_OF else Literal(value)))
        val = value.replace("'", "\\'")
        cy.append(f"MATCH (e:{ent} {{id:'{ent}'}}) SET e.{field}='{val}';")
        for f in evs:
            n_ev += 1
            ev = INST[f"evidence_{n_ev}"]
            g.add((ev, RDF.type, EX.Evidence)); g.add((ev, EX.supports_entity, ind(ent))); g.add((ev, EX.supports_field, Literal(field)))
            g.add((ev, EX.doc, INST['doc_' + f.doc_id])); g.add((ev, EX.page, Literal(f.page, datatype=XSD.integer)))
            g.add((ev, EX.span, Literal(f.span))); g.add((ev, EX.bbox, Literal(json.dumps(f.bbox))))
            g.add((ev, EX.status, Literal(f.status)))
            span = f.span.replace("\\", "").replace("'", "\\'").replace("\n", " ")[:300]
            cy.append(f"MATCH (e:{ent} {{id:'{ent}'}}),(d:Document {{id:'{f.doc_id}'}}) "
                      f"CREATE (v:Evidence {{id:{n_ev}, field:'{field}', page:{f.page}, bbox:'{json.dumps(f.bbox)}', span:'{span}', status:'{f.status}'}}) "
                      f"MERGE (v)-[:SUPPORTS]->(e) MERGE (v)-[:FROM]->(d);")
    stats = {
        "entities": len(entities), "documents": len({f.doc_id for f in loaded}), "workflow_stages": len(STAGES),
        "property_assertions": len(assertions), "evidence_nodes": n_ev, "rdf_triples": len(g),
        "provenance_completeness": 1.0 if all(assertions.values()) else 0.0,
        "assertions_with_multiple_evidence": sum(len(v) > 1 for v in assertions.values()),
        "human_verified_facts": sum(f.status == "human_verified" for f in loaded),
        "canonical_keys": {e: keys.get(e, (None, None))[1] or "none (fields a key needs are missing)" for e in entities},
    }
    return g, cy, stats


def save(facts: list, out_dir=None) -> dict:
    out_dir = out_dir or config.PROCESSED / "kg"
    out_dir.mkdir(parents=True, exist_ok=True)
    g, cy, stats = build(facts)
    g.serialize(out_dir / "kg.ttl", format="turtle")
    (out_dir / "kg.cypher").write_text("\n".join(cy) + "\n", encoding="utf-8")
    (out_dir / "kg_stats.json").write_text(json.dumps(stats, indent=1))
    return stats

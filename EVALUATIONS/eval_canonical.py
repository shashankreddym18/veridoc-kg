"""E12: cross-document agreement under surface variation (deterministic canonical forms vs similarity).

    python EVALUATIONS/eval_canonical.py          -> EVALUATIONS/results/e12_canonical.json

The same value is often printed differently on two documents of one case ("Acme Widgets, Inc." /
"ACME WIDGETS INC", "02/01/2023" / "February 1, 2023", "$1,000.00" / "$1000", "Oregon" / "OR").
The cross-document check must not call these a conflict, and must still catch real differences,
including near misses ("$1,000" vs "$10,000", one day apart, "Acme Widget" vs "Acme Widgets",
a truncated or redacted name). This test feeds the check pairs of values with known answers and counts
  false conflict   the same value, printed two ways, judged different (a correct fact quarantined)
  missed conflict  two different values judged the same (a wrong fact loaded)
for three ways of comparing: surface text, similarity of normalized text (the earlier rule, token-set
ratio >= 90) and canonical forms (veridoc/keys.py, the current rule).

Values come from the synthetic personas (test seed), so no real data is involved; the variants and the
near misses are generated by the fixed rules below, seed 12.
"""
from __future__ import annotations
import json, random, sys
from collections import defaultdict
from datetime import date, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "CODE"))
from veridoc import config, synthetic                     # noqa: E402
from veridoc.verifier import same_value                   # noqa: E402

OUT = config.ROOT / "EVALUATIONS" / "results" / "e12_canonical.json"
METHODS = ("surface", "fuzzy", "canonical")
STATE_NAME = {"OR": "Oregon", "AZ": "Arizona", "CA": "California", "TX": "Texas", "WA": "Washington", "NY": "New York",
              "IL": "Illinois", "FL": "Florida", "CO": "Colorado", "GA": "Georgia", "OH": "Ohio", "PA": "Pennsylvania",
              "NC": "North Carolina", "MI": "Michigan", "NJ": "New Jersey", "VA": "Virginia", "MA": "Massachusetts"}
MON = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]


def date_variants(d: date) -> list:
    m = MON[d.month - 1]
    return [f"{d.month:02d}/{d.day:02d}/{d.year}", f"{d.month}/{d.day}/{d.year}", f"{m} {d.day}, {d.year}",
            f"{m[:3]}. {d.day}, {d.year}", f"{m[:3]} {d.day} {d.year}"]


def money_variants(x: float) -> list:
    return [f"${x:,.2f}", f"${x:,.0f}" if x == int(x) else f"${x:.2f}", f"{x:,.2f}", f"$ {x:,.2f}", f"${x:.2f}"]


def name_variants(n: str) -> list:
    base = n.replace(",", "")
    core = base
    for sfx in (" Inc.", " Inc", " LLC", " Corp.", " Co."):
        if core.endswith(sfx):
            core = core[: -len(sfx)]
    return [n, n.upper(), core + ", Inc.", core.upper() + " INC", "The " + core + " LLC", core]


def state_variants(s: str) -> list:
    return [s, STATE_NAME.get(s, s), STATE_NAME.get(s, s).upper()] if s in STATE_NAME else [s]


def freq_variants(f: str) -> list:
    return [f, f.lower(), f.upper()]


def near_miss(field: str, v, rng):
    """A different value that looks close to v."""
    if field.endswith("date"):
        return v + timedelta(days=rng.choice([1, -1, 31]))
    if field in ("face_amount", "annual_premium"):
        return rng.choice([v * 10, v + 1, v / 10 if v >= 10 else v + 100])
    if field == "group_name":
        core = v.split()[0]
        return rng.choice([v + " Holdings", v.rstrip("s") if v.endswith("s") else v + "s", core])   # longer, one letter, truncated
    if field == "ee_state":
        return rng.choice([s for s in STATE_NAME if s != v])
    return None


def cases(n: int = 60, seed: int = 12) -> list:
    rng = random.Random(seed)
    prng = random.Random(synthetic.SEEDS["test"])
    people = [synthetic.persona(prng, i, "e12")["values"] for i in range(n)]
    out = []
    for p in people:
        mdy = lambda s: date(int(s[6:]), int(s[:2]), int(s[3:5]))
        vals = {"group_name": p["group_name"], "date_of_birth": mdy(p["date_of_birth"]), "date_of_hire": mdy(p["date_of_hire"]),
                "face_amount": float(p["face_amount"].strip("$").replace(",", "")), "annual_premium": float(p["annual_premium"]),
                "ee_state": p["ee_state"], "payroll_frequency": p["payroll_frequency"]}
        for field, v in vals.items():
            var = (date_variants if field.endswith("date_of_birth") or field.endswith("date_of_hire") else
                   money_variants if field in ("face_amount", "annual_premium") else
                   name_variants if field == "group_name" else state_variants if field == "ee_state" else freq_variants)
            forms = var(v)
            if len(forms) > 1:                                         # same value, two printed forms
                a, b = rng.sample(forms, 2)
                out.append({"field": field, "a": a, "b": b, "same": True, "kind": "variant"})
            w = near_miss(field, v, rng)
            if w is not None and w != v:                               # different value, printed in any form
                out.append({"field": field, "a": rng.choice(forms), "b": rng.choice(var(w)), "same": False, "kind": "near miss"})
    return out


def main() -> None:
    cs = cases()
    res = {m: defaultdict(lambda: defaultdict(int)) for m in METHODS}
    examples = {m: [] for m in METHODS}
    for c in cs:
        for m in METHODS:
            ok, _ = same_value(c["field"], [c["a"], c["b"]], m)
            r = res[m][c["field"]]
            if c["same"]:
                r["same_pairs"] += 1; r["false_conflict"] += (not ok)
            else:
                r["different_pairs"] += 1; r["missed_conflict"] += ok
            if ok != c["same"] and len(examples[m]) < 8:
                examples[m].append(f'{c["field"]}: {c["a"]!r} vs {c["b"]!r} ({"same" if c["same"] else "different"})')
    summary = {}
    for m in METHODS:
        t = defaultdict(int)
        for r in res[m].values():
            for k, v in r.items():
                t[k] += v
        summary[m] = {"false_conflict_rate": round(t["false_conflict"] / t["same_pairs"], 3),
                      "missed_conflict_rate": round(t["missed_conflict"] / t["different_pairs"], 3),
                      "false_conflicts": t["false_conflict"], "missed_conflicts": t["missed_conflict"],
                      "same_pairs": t["same_pairs"], "different_pairs": t["different_pairs"]}
    out = {"_note": __doc__.strip().splitlines()[0], "pairs": len(cs), "summary": summary,
           "by_field": {m: {f: dict(r) for f, r in res[m].items()} for m in METHODS}, "errors_sample": examples}
    OUT.write_text(json.dumps(out, indent=1))
    for m in METHODS:
        s = summary[m]
        print(f"   {m:10s} false conflicts {s['false_conflicts']:3d}/{s['same_pairs']} ({s['false_conflict_rate']:.1%})   "
              f"missed conflicts {s['missed_conflicts']:3d}/{s['different_pairs']} ({s['missed_conflict_rate']:.1%})")
        for e in examples[m][:4]:
            print("        ", e)
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
